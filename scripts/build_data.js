const formatData = (rawList, levelPrefix, level) => {
  return rawList.map((item, index) => {
    const id = `${levelPrefix}_${String(index + 1).padStart(3, '0')}`;
    return {
      id,
      word: item.w,
      reading: item.r,
      romaji: item.ro,
      partOfSpeech: item.pos,
      meaning: item.m,
      level,
      example: item.ex,
      exampleMeaning: item.exm
    };
  });
};

