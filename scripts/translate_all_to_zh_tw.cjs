function cleanToZh(word, reading, rawMeaning, pos) {
  // Check exact dictionary
  if (zhMap[word]) {
    return zhMap[word];
  }
  if (zhMap[reading]) {
    return zhMap[reading];
  }

  let text = rawMeaning;
  for (const [re, rep] of termDict) {
    text = text.replace(re, rep);
  }

  // Remove leftover english parentheticals, notes, tags
  text = text
    .replace(/\(.*?\)/g, '')
    .replace(/\[.*?\]/g, '')
    .replace(/v\.i\.|v\.t\.|adj\.|noun|adv\./gi, '')
    .replace(/[a-zA-Z]/g, '')
    .replace(/[,;，、]+/g, '、')
    .replace(/^、|、$/g, '')
    .trim();

  if (!text) {
    text = word;
  }

  // Default natural example
  let ex = '';
  let zh = '';
  if (pos === '動詞') {
    ex = `毎日${word}ことがあります。`;
    zh = `每天都有${text}的時候。`;
  } else if (pos === 'い形容詞') {
    ex = `この本はとても${word}です。`;
    zh = `這本書非常${text}。`;
  } else if (pos === 'な形容詞') {
    ex = `ここはとても${word}な場所です。`;
    zh = `這裡是個非常${text}的地方。` ;
  } else if (pos === '副詞') {
    ex = `${word}勉強します。`;
    zh = `${text}認真學習。`;
  } else {
    ex = `ここに${word}があります。`;
    zh = `這裡有${text}。`;
  }

  return { m: text, ex, zh };
}

function processList(list) {
  return list.map(item => {
    const res = cleanToZh(item.word, item.reading, item.meaning, item.partOfSpeech);
    return {
      ...item,
      meaning: res.m,
      example: res.ex || item.example,
      exampleMeaning: res.zh || item.exampleMeaning
    };
  });
}

